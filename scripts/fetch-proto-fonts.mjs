/**
 * Downloads the webfonts used by the IDENTITY PROTOTYPES into mockups/fonts/
 * and generates mockups/fonts.css.
 *
 * Deliberately separate from fetch-fonts.mjs. That script owns the fonts the
 * real site ships; this one owns throwaway families that exist only so the
 * prototypes can be judged with real type instead of system fallbacks. When a
 * direction is picked, promote its families into fetch-fonts.mjs and delete
 * this script together with mockups/fonts/.
 *
 *   node scripts/fetch-proto-fonts.mjs
 *
 * All families are SIL Open Font License 1.1, so redistribution is fine.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const OUT_FONTS = 'mockups/fonts';
const OUT_CSS = 'mockups/fonts.css';

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

// Roman only. The prototypes use no italics, and every skipped face is
// weight the browser does not have to pull before the page can be judged.
const FAMILIES = [
  {
    name: 'Instrument Sans',
    file: 'instrument-sans',
    url: 'https://fonts.googleapis.com/css2?family=Instrument+Sans:wght@400..700&display=swap',
  },
  {
    name: 'JetBrains Mono',
    file: 'jetbrains-mono',
    url: 'https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@100..800&display=swap',
  },
  {
    name: 'Inter',
    file: 'inter',
    url: 'https://fonts.googleapis.com/css2?family=Inter:wght@100..900&display=swap',
  },
  {
    name: 'Bodoni Moda',
    file: 'bodoni-moda',
    url: 'https://fonts.googleapis.com/css2?family=Bodoni+Moda:opsz,wght@6..96,400..900&display=swap',
  },
  {
    name: 'Archivo',
    file: 'archivo',
    url: 'https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,100..900&display=swap',
  },
];

// latin-ext carries the Turkish and German characters the name itself needs
// (Ö in "Özer", ü in "München"). Dropping it would break the wordmark.
const WANTED = new Set(['latin', 'latin-ext']);

await mkdir(OUT_FONTS, { recursive: true });

const blocks = [];

for (const fam of FAMILIES) {
  const res = await fetch(fam.url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${fam.name}: font CSS request failed (${res.status})`);
  const css = await res.text();

  const chunks = css.split('/*').slice(1);
  let kept = 0;

  for (const chunk of chunks) {
    const subset = chunk.slice(0, chunk.indexOf('*/')).trim();
    if (!WANTED.has(subset)) continue;
    if (/font-style:\s*italic/.test(chunk)) continue;

    const src = chunk.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    const range = chunk.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
    const weight = chunk.match(/font-weight:\s*([^;]+);/)?.[1]?.trim() ?? '400';
    if (!src || !range) continue;

    const filename = `${fam.file}-${subset}.woff2`;
    const bin = await fetch(src, { headers: { 'User-Agent': UA } });
    if (!bin.ok) throw new Error(`${filename}: download failed (${bin.status})`);
    const buf = Buffer.from(await bin.arrayBuffer());
    await writeFile(join(OUT_FONTS, filename), buf);
    kept++;

    blocks.push(
      `@font-face {\n` +
        `  font-family: "${fam.name}";\n` +
        `  font-style: normal;\n` +
        `  font-weight: ${weight};\n` +
        `  font-display: swap;\n` +
        `  src: url("./fonts/${filename}") format("woff2");\n` +
        `  unicode-range: ${range};\n` +
        `}`
    );
    console.log(`  ${filename}  ${(buf.length / 1024).toFixed(1)} KB`);
  }
  if (!kept) throw new Error(`${fam.name}: no matching subsets found`);
  console.log(`${fam.name}: ${kept} file(s)`);
}

const header =
  `/* GENERATED by scripts/fetch-proto-fonts.mjs - do not edit by hand.\n` +
  `   Prototype-only families, SIL Open Font License 1.1.\n` +
  `   Delete with mockups/fonts/ once a direction is chosen. */\n\n`;

await writeFile(OUT_CSS, header + blocks.join('\n\n') + '\n');
console.log(`\nwrote ${OUT_CSS} (${blocks.length} @font-face rules)`);
